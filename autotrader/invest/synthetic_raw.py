"""Synthetic RAW fixtures in real source formats, for the offline pipeline. Nothing here is real data.

Writes a raw store (`adapters.raw`) with, for twelve invented companies and an invented index fund:
* EDGAR submissions JSON (one company also with an older page), `-index-headers` pages, primary documents and
  EX-99.1 releases, company-facts JSON and `company_tickers.json`;
* two N-PORT-P reports (one public before the freeze, one after) and a FIXTURE mapping review (labelled: not a
  person's review);
* unadjusted daily bars and a corporate-actions file (the synthetic prices of `synthetic.build`).
The fiscal calendars and XBRL shapes exercise the pipeline: calendar, September and June fiscal years and a 52/53-week
year; quarterly, year-to-date and annual periods; comparatives repeated in later filings; a 10-K/A restatement filed
after a cutoff; a two-class share count; an EPS entry in a wrong unit; an unsupported action after the pilot.
"""
from __future__ import annotations

import json
import tempfile
from datetime import date, datetime, timedelta, timezone
from decimal import ROUND_HALF_EVEN, Decimal
from pathlib import Path

from stockpilot.clock import ET

from . import synthetic
from .adapters.raw import write_raw_store
from .registration import BENCHMARK
from .universe import select_universe

RETRIEVED = "2032-01-05T12:00:00+00:00"
FREEZE = datetime(2030, 12, 15, 12, 0, tzinfo=ET)
SERIES = "Synthetic 500 Index Fund"
FUND_CIK = 9900000099
D2 = Decimal("0.01")


def _q2(x) -> Decimal:
    return Decimal(str(x)).quantize(D2, rounding=ROUND_HALF_EVEN)


def _last_saturday(y: int, m: int) -> date:
    d = date(y, m + 1, 1) - timedelta(days=1) if m < 12 else date(y, 12, 31)
    return d - timedelta(days=(d.weekday() - 5) % 7)


def _fiscal_quarters(k: int) -> list[dict]:
    """Fiscal quarters (fy, q, start, end) covering filings from 2029 to 2031."""
    out = []
    for fy in range(2028, 2033):
        if k == 10:                                            # 52/53-week year ending the last Saturday of December
            fye_prev, fye = _last_saturday(fy - 1, 12), _last_saturday(fy, 12)
            s = fye_prev + timedelta(days=1)
            ends = [s + timedelta(weeks=13 * i) - timedelta(days=1) for i in (1, 2, 3)] + [fye]
        else:
            fye_month = {9: 9, 11: 6}.get(k, 12)
            first = date(fy - 1 if fye_month != 12 else fy, fye_month % 12 + 1, 1)
            s = first
            ends = []
            for i in range(4):
                mm = (first.month - 1 + 3 * (i + 1)) % 12
                yy = first.year + (first.month - 1 + 3 * (i + 1)) // 12
                ends.append(date(yy, mm + 1, 1) - timedelta(days=1) if mm < 12 else date(yy, 12, 31))
        start = s
        for q, e in enumerate(ends, 1):
            out.append({"fy": fy, "q": q, "start": start, "end": e, "fy_start": s})
            start = e + timedelta(days=1)
    return out


def _accepted(d: date, hh: int, mm: int) -> datetime:
    return datetime(d.year, d.month, d.day, hh, mm, tzinfo=ET)


def _z(t: datetime) -> str:
    return t.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")


def _header(acc: str, cik: int, name: str, form: str, t: datetime, items: list[str], docs: list[tuple]) -> str:
    rows = "".join(f"&lt;DOCUMENT&gt;\n&lt;TYPE&gt;{ty}\n&lt;SEQUENCE&gt;{i + 1}\n&lt;FILENAME&gt;{fn}\n"
                   for i, (ty, fn) in enumerate(docs))
    its = "".join(f"ITEM INFORMATION:\t\t{i}\n" for i in items)
    return (f"<HTML><HEAD><TITLE>SEC EDGAR Submission {acc}</TITLE></HEAD><BODY><PRE>"
            f"&lt;SEC-HEADER&gt;{acc}.hdr.sgml : {t:%Y%m%d}\n&lt;ACCEPTANCE-DATETIME&gt;{t:%Y%m%d%H%M%S}\n"
            f"ACCESSION NUMBER:\t\t{acc}\nCONFORMED SUBMISSION TYPE:\t{form}\n{its}"
            f"FILER:\n\tCOMPANY DATA:\n\t\tCOMPANY CONFORMED NAME:\t\t\t{name}\n\t\tCENTRAL INDEX KEY:\t\t\t{cik:010d}\n"
            f"&lt;/SEC-HEADER&gt;\n{rows}</PRE></BODY></HTML>")


def _doc(name: str, form: str, rev_q: Decimal, growth: int, margin: int, impairment: int, customer: int) -> str:
    toc = ("<p>Table of Contents</p><p>Item 1A. Risk Factors</p>"
           "<p>Item 7. Management's Discussion and Analysis of Financial Condition and Results of Operations</p>")
    mda = (f"<h2>Management's Discussion and Analysis of Financial Condition and Results of Operations</h2>"
           f"<p>{name} is an invented company used to test this pipeline. Nothing in this document describes a real "
           f"business, and every figure in it was generated by a program for an offline test of passage selection.</p>"
           f"<p>Revenue for the quarter was ${rev_q:,} million, an increase of {growth}% from the same quarter a year "
           f"earlier. Growth came mainly from existing customers renewing larger contracts.</p>"
           f"<p>Operating margin was {margin}% for the quarter. Higher input costs reduced gross margin by 2 percentage "
           f"points compared with the prior year, and we expect cost pressure to continue.</p>"
           f"<p>We recorded an impairment charge of ${impairment} million related to a discontinued product line. The "
           f"charge reduced operating income for the period and may recur if demand weakens further.</p>")
    risk = ("<h2>Risk Factors</h2>"
            f"<p>Our largest customer accounted for {customer}% of revenue. The loss of this customer, or a material "
            f"reduction in its orders, would materially reduce our revenue, margins and results of operations. "
            f"Customer concentration also limits our pricing power at contract renewals.</p>")
    body = toc + (risk + mda if form == "10-K" else mda)
    return f"<html><body><h1>{name} {form}</h1>{body}</body></html>"


def _release(name: str, rev_q: Decimal, growth: int) -> str:
    return (f"<html><body><p>{name} reports quarterly results (invented company; synthetic fixture).</p>"
            f"<p>Revenue for the quarter was ${rev_q:,} million, up {growth}% from a year earlier, and diluted earnings "
            f"per share rose compared with the prior-year quarter.</p>"
            f"<p>The company recorded a decline of 3% in new orders during the quarter, which management attributed to "
            f"longer customer approval cycles; it expects order growth to resume next year.</p></body></html>")


def build_raw(d: Path) -> str:
    """Write the raw fixture store; returns its manifest's SHA-256."""
    files: dict[str, tuple] = {}

    def put(rel, data, url, kind):
        files[rel] = (data if isinstance(data, bytes) else data.encode(), url, RETRIEVED, kind)

    rows, cmap = synthetic.nport_rows()
    members = select_universe(rows, cmap, size=12)
    tickers = {str(i): {"cik_str": int(m["cik"]), "ticker": m["symbol"], "title": m["name"]}
               for i, m in enumerate(members)}
    put("edgar/company_tickers.json", json.dumps(tickers), "https://www.sec.gov/files/company_tickers.json",
        "edgar_tickers")
    for k, m in enumerate(members):
        cik, name, sym = int(m["cik"]), m["name"], m["symbol"]
        quarters = _fiscal_quarters(k)
        base = Decimal(2000 + 700 * k)
        rev, ni, eps, sh = {}, {}, {}, {}
        for t, qq in enumerate(quarters):
            r = (base * Decimal(1.012) ** t * Decimal([0.97, 1.0, 1.01, 1.03][qq["q"] - 1])).quantize(Decimal(1))
            n = (r * Decimal(9 + (k + t) % 8) / 100).quantize(Decimal(1))
            shares = 900_000_000 + 37_000_000 * k + 2_000_000 * t
            rev[(qq["fy"], qq["q"])], ni[(qq["fy"], qq["q"])], sh[(qq["fy"], qq["q"])] = r, n, shares
            eps[(qq["fy"], qq["q"])] = _q2(n * 1_000_000 / shares)
        by = {(q["fy"], q["q"]): q for q in quarters}
        entries, facts = [], {"Revenues": [], "NetIncomeLoss": [], "EarningsPerShareDiluted": [], "shares": []}
        seq = 0

        def add_fact(concept, start, end, val, accn, fy, fp, form, filed, unit=None, facts=facts):
            if concept in ("Revenues", "NetIncomeLoss"):
                val = val * 1_000_000                                   # XBRL reports USD, not millions
            facts[concept].append({"start": start.isoformat() if start else None, "end": end.isoformat(),
                                   "val": float(val) if concept == "EarningsPerShareDiluted" else int(val),
                                   "accn": accn, "fy": fy, "fp": fp, "form": form, "filed": filed.isoformat(),
                                   **({"unit": unit} if unit else {})})

        for qq in quarters:
            fy, q, end = qq["fy"], qq["q"], qq["end"]
            if end < date(2028, 12, 1) or end > date(2031, 10, 31):
                continue
            ytd = [by[(fy, i)] for i in range(1, q + 1)]
            prior = by.get((fy - 1, q))
            prior_ytd = [by[(fy - 1, i)] for i in range(1, q + 1) if (fy - 1, i) in by]
            # 8-K Item 2.02 release (pre-market), then the periodic report
            for form, lag, hh in (("8-K", 24, 7), ("10-K" if q == 4 else "10-Q", 52 if q == 4 else 38, 16)):
                seq += 1
                day = end + timedelta(days=lag)
                acc = f"{cik:010d}-{day.year % 100:02d}-{seq:06d}"
                t = _accepted(day, hh, 5)
                if t.astimezone(timezone.utc).date() > date(2031, 12, 31):
                    continue
                g = 3 + (k + q) % 9
                prim = f"{sym.lower()}-{end:%Y%m%d}{'' if form != '8-K' else '-8k'}.htm"
                docs = [(form, prim)] + ([("EX-99.1", f"{sym.lower()}-{end:%Y%m%d}-ex991.htm")] if form == "8-K" else [])
                items = ["2.02", "9.01"] if form == "8-K" else []
                entries.append({"accessionNumber": acc, "filingDate": day.isoformat(), "reportDate": end.isoformat(),
                                "acceptanceDateTime": _z(t), "form": form, "items": ",".join(items),
                                "primaryDocument": prim})
                nod = acc.replace("-", "")
                put(f"edgar/headers/{acc}-index-headers.html", _header(acc, cik, name, form, t, items, docs),
                    f"https://www.sec.gov/Archives/edgar/data/{cik}/{nod}/{acc}-index-headers.html", "edgar_header")
                if form == "8-K":
                    put(f"edgar/docs/{nod}/{docs[0][1]}", f"<html><body><p>{name} 8-K cover.</p></body></html>",
                        f"https://www.sec.gov/Archives/edgar/data/{cik}/{nod}/{docs[0][1]}", "edgar_document")
                    put(f"edgar/docs/{nod}/{docs[1][1]}", _release(name, rev[(fy, q)], g),
                        f"https://www.sec.gov/Archives/edgar/data/{cik}/{nod}/{docs[1][1]}", "edgar_document")
                    continue
                put(f"edgar/docs/{nod}/{prim}", _doc(name, form, rev[(fy, q)], g, 10 + (k + q) % 8, 10 + k, 10 + k),
                    f"https://www.sec.gov/Archives/edgar/data/{cik}/{nod}/{prim}", "edgar_document")
                fp = "FY" if q == 4 else f"Q{q}"
                if q == 4:
                    for yy in (fy, fy - 1, fy - 2):
                        qs = [by.get((yy, i)) for i in (1, 2, 3, 4)]
                        if all(qs):
                            add_fact("Revenues", qs[0]["start"], qs[3]["end"], sum(rev[(yy, i)] for i in (1, 2, 3, 4)),
                                     acc, fy, fp, form, day)
                            add_fact("NetIncomeLoss", qs[0]["start"], qs[3]["end"],
                                     sum(ni[(yy, i)] for i in (1, 2, 3, 4)), acc, fy, fp, form, day)
                            add_fact("EarningsPerShareDiluted", qs[0]["start"], qs[3]["end"],
                                     sum(eps[(yy, i)] for i in (1, 2, 3, 4)), acc, fy, fp, form, day)
                else:
                    for cur, pr in ((qq, prior),):
                        for qd in (cur, pr):
                            if qd is None:
                                continue
                            kk = (qd["fy"], qd["q"])
                            add_fact("Revenues", qd["start"], qd["end"], rev[kk], acc, fy, fp, form, day)
                            add_fact("NetIncomeLoss", qd["start"], qd["end"], ni[kk], acc, fy, fp, form, day)
                            add_fact("EarningsPerShareDiluted", qd["start"], qd["end"], eps[kk], acc, fy, fp, form, day)
                    if q > 1:
                        for span in (ytd, prior_ytd):
                            if len(span) == q:
                                keys = [(s["fy"], s["q"]) for s in span]
                                add_fact("Revenues", span[0]["start"], span[-1]["end"], sum(rev[x] for x in keys),
                                         acc, fy, fp, form, day)
                                add_fact("NetIncomeLoss", span[0]["start"], span[-1]["end"], sum(ni[x] for x in keys),
                                         acc, fy, fp, form, day)
                                add_fact("EarningsPerShareDiluted", span[0]["start"], span[-1]["end"],
                                         sum(eps[x] for x in keys), acc, fy, fp, form, day)
                cover = day - timedelta(days=5)
                classes = (0.8, 0.2) if k == 0 else (1.0,)              # SYNTH01 reports two share classes
                for share in classes:
                    add_fact("shares", None, cover, int(sh[(fy, q)] * share), acc, fy, fp, form, day)
                if k == 4:                                               # a wrong-unit EPS entry: must be excluded
                    add_fact("EarningsPerShareDiluted", qq["start"], end, 1, acc, fy, fp, form, day, unit="pure")
        if k == 2:                                                       # SYNTH03: a 10-K/A restating FY2030 revenue
            seq += 1
            day = date(2031, 4, 15)
            acc = f"{cik:010d}-31-{seq:06d}"
            t = _accepted(day, 16, 5)
            fyq = [by[(2030, i)] for i in (1, 2, 3, 4)]
            entries.append({"accessionNumber": acc, "filingDate": day.isoformat(), "reportDate": fyq[3]["end"].isoformat(),
                            "acceptanceDateTime": _z(t), "form": "10-K/A", "items": "", "primaryDocument": "amend.htm"})
            add_fact("Revenues", fyq[0]["start"], fyq[3]["end"], sum(rev[(2030, i)] for i in (1, 2, 3, 4)) * Decimal("1.05"),
                     acc, 2030, "FY", "10-K/A", day)
        entries.sort(key=lambda e: e["acceptanceDateTime"], reverse=True)
        cols = ("accessionNumber", "filingDate", "reportDate", "acceptanceDateTime", "form", "items", "primaryDocument")
        recent, older = (entries[:12], entries[12:]) if k == 0 else (entries, [])
        main = {"cik": f"{cik:010d}", "name": name, "tickers": [sym],
                "filings": {"recent": {c: [e[c] for e in recent] for c in cols},
                            "files": [{"name": f"CIK{cik:010d}-submissions-001.json"}] if older else []}}
        put(f"edgar/submissions/CIK{cik:010d}.json", json.dumps(main),
            f"https://data.sec.gov/submissions/CIK{cik:010d}.json", "edgar_submissions")
        if older:
            put(f"edgar/submissions/CIK{cik:010d}-submissions-001.json", json.dumps({c: [e[c] for e in older] for c in cols}),
                f"https://data.sec.gov/submissions/CIK{cik:010d}-submissions-001.json", "edgar_submissions")
        units = {}
        for concept, rowsf in facts.items():
            for r in rowsf:
                u = r.pop("unit", None) or {"EarningsPerShareDiluted": "USD/shares", "shares": "shares"}.get(concept, "USD")
                units.setdefault(concept, {}).setdefault(u, []).append(r)
        cf = {"cik": cik, "entityName": name,
              "facts": {"dei": {"EntityCommonStockSharesOutstanding": {"units": units.get("shares", {})}},
                        "us-gaap": {c: {"units": units[c]} for c in ("Revenues", "NetIncomeLoss", "EarningsPerShareDiluted")}}}
        put(f"edgar/companyfacts/CIK{cik:010d}.json", json.dumps(cf),
            f"https://data.sec.gov/api/xbrl/companyfacts/CIK{cik:010d}.json", "edgar_companyfacts")

    # the fund: two N-PORT-P reports, one public before the freeze
    fund_entries = []
    for seq, (rep, day) in enumerate((("2030-09-30", date(2030, 11, 27)), ("2030-12-31", date(2031, 2, 26))), 1):
        acc = f"{FUND_CIK:010d}-{day.year % 100:02d}-{seq:06d}"
        nod = acc.replace("-", "")
        holdings = "".join(
            f"<invstOrSec><name>{r['name']}</name><lei>{r['lei']}</lei><title>{r['name']}</title><cusip>{r['cusip']}</cusip>"
            + (f"<identifiers><ticker value=\"{cmap[r['cusip']]['symbol']}\"/></identifiers>" if r["cusip"] in cmap else "")
            + f"<valUSD>{r['value_usd']}</valUSD><assetCat>{r['asset_cat']}</assetCat></invstOrSec>" for r in rows)
        xml = (f"<?xml version=\"1.0\"?><edgarSubmission xmlns=\"http://www.sec.gov/edgar/nport\"><formData>"
               f"<genInfo><seriesName>{SERIES}</seriesName><repPdDate>{rep}</repPdDate></genInfo>"
               f"<invstOrSecs>{holdings}</invstOrSecs></formData></edgarSubmission>")
        put(f"nport/{nod}/primary_doc.xml", xml, f"https://www.sec.gov/Archives/edgar/data/{FUND_CIK}/{nod}/primary_doc.xml",
            "nport_xml")
        fund_entries.append({"accessionNumber": acc, "filingDate": day.isoformat(), "reportDate": rep,
                             "acceptanceDateTime": _z(_accepted(day, 10, 0)), "form": "NPORT-P", "items": "",
                             "primaryDocument": "primary_doc.xml"})
    cols = ("accessionNumber", "filingDate", "reportDate", "acceptanceDateTime", "form", "items", "primaryDocument")
    put(f"edgar/submissions/CIK{FUND_CIK:010d}.json",
        json.dumps({"cik": f"{FUND_CIK:010d}", "name": "Synthetic Index Funds", "tickers": [],
                    "filings": {"recent": {c: [e[c] for e in fund_entries] for c in cols}, "files": []}}),
        f"https://data.sec.gov/submissions/CIK{FUND_CIK:010d}.json", "edgar_submissions")
    put("review/universe_review.json", json.dumps({
        "reviewer": "FIXTURE (scripted; not a person's review)", "reviewed_at": "2030-12-10T12:00:00-05:00",
        "fixture": True, "rows": [{"cusip": m["cusip"], "symbol": m["symbol"], "cik": m["cik"], "approved": True}
                                  for m in members]}), "fixture://universe-review", "universe_review")

    # market data: the synthetic prices and actions as unadjusted vendor bars
    with tempfile.TemporaryDirectory() as tmp:
        synthetic.build(Path(tmp) / "d")
        prices = json.loads((Path(tmp) / "d" / "prices.json").read_text())
        acts = json.loads((Path(tmp) / "d" / "actions.json").read_text())
    for sym in [BENCHMARK] + [m["symbol"] for m in members]:
        bars = [{"t": day, "o": row["open"], "c": row["close"]} for day, row in sorted(prices[sym].items())]
        put(f"market/bars/{sym}.json", json.dumps({"symbol": sym, "adjustment": "raw", "bars": bars}),
            f"fixture://bars/{sym}", "price_bars")
    put("market/corporate_actions.json", json.dumps({
        "cash_dividends": [{"symbol": x["symbol"], "ex_date": x["ex_date"], "payable_date": x["pay_date"],
                            "rate": x["amount"]} for x in acts["dividends"]],
        "forward_splits": [{"symbol": x["symbol"], "ex_date": x["ex_date"], "old_rate": x["den"], "new_rate": x["num"]}
                           for x in acts["splits"]],
        "cash_mergers": [{"acquiree_symbol": "SYNTH12", "effective_date": "2032-06-01", "rate": "60.00"}]}),
        "fixture://corporate-actions", "corporate_actions")
    return write_raw_store(d, files, synthetic=True)
